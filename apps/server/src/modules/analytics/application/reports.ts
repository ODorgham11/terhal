import { AppError } from "../../../platform/errors/app-error";
import { logger } from "../../../platform/logger/logger";
import { SIGNED_URL_LIFETIME, storage } from "../../../platform/storage/index";
import {
  cairoMonthOf,
  isMonthOver,
  monthDays,
  monthLabel,
  previousMonth,
  reportKey,
  type Month,
} from "../domain/months";
import { analytics } from "./metrics";
import { buildWorkbook } from "./workbook";

// The monthly report (Y3 a): the previous month's workbook, written on the 1st (Cairo time) by a scheduled job and
// regenerated by staff on request. A month has one key, so regenerating replaces the file and the same row; doing it
// twice gives the same result. The file goes through platform/storage only: a local folder in development, the R2
// bucket everywhere else, picked by STORAGE_DRIVER.

const XLSX = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";

const toReport = (document: AnalyticsDocument): AnalyticsReport => ({
  year: document.year,
  month: document.month,
  size: document.size,
  createdAt: document.createdAt.toISOString(),
  generatedAt: document.updatedAt.toISOString(),
});

const notFound = () =>
  new AppError({ code: "NOT_FOUND", status: 404, detail: "This month has no report yet." });

// Newest month first. A handful a year, so the list isn't paged.
export const listReports = async () => {
  const documents = await prisma.analyticsDocument.findMany({
    orderBy: [{ year: "desc" }, { month: "desc" }],
  });
  return { data: documents.map(toReport), nextCursor: null };
};

export const reportLink = async (target: Month, now = new Date()): Promise<AnalyticsReportLink> => {
  const document = await prisma.analyticsDocument.findUnique({
    where: { year_month: target },
  });
  if (!document) throw notFound();
  return {
    year: document.year,
    month: document.month,
    url: await storage.signedUrl(document.key, SIGNED_URL_LIFETIME),
    expiresAt: new Date(now.getTime() + SIGNED_URL_LIFETIME * 1000).toISOString(),
  };
};

// Writes the month's workbook and records it. Only a month that's over has a report: one still running would block
// its trips from being reopened (T8 a) while they can still change.
export const generateReport = async (target: Month, now = new Date()) => {
  if (!isMonthOver(target, now)) {
    throw new AppError({
      code: "REPORT_MONTH_NOT_OVER",
      status: 422,
      detail: `${monthLabel(target)} isn't over yet (Cairo time).`,
      extensions: { ...target },
    });
  }
  const figures = await analytics({ ...monthDays(target), groupBy: "day" });
  const body = await buildWorkbook(target, figures, now);
  const key = reportKey(target);
  // The file first: a failure leaves the previous row pointing at the previous file (or no row), never a row without
  // a file.
  await storage.put(key, body, XLSX);
  const data = { bucket: storage.bucket, key, size: body.byteLength };
  const save = () =>
    prisma.analyticsDocument.upsert({
      where: { year_month: target },
      create: { ...target, ...data },
      update: data,
    });
  let document: AnalyticsDocument;
  try {
    document = await save();
  } catch (error) {
    // Two generations of a new month at once: the other one created the row, so update it.
    if (sqlState(error) !== "23505") throw error;
    document = await save();
  }
  logger.info({ month: monthLabel(target), size: body.byteLength }, "monthly report generated");
  return toReport(document);
};

// --- The scheduled job ---

export const MONTHLY_REPORT_JOB = "monthly-report";

// 02:00 on the 1st, Cairo time, for the month that just ended.
export const monthlyReportSchedule = { pattern: "0 2 1 * *", tz: "Africa/Cairo" };

const jobOptions = { attempts: 5, backoff: { type: "exponential", delay: 60_000 } };

// The month the job reports on, if it has no report yet. A retry, or a run after staff already generated it, changes
// nothing.
export const generateDueReport = async (now = new Date()) => {
  const target = previousMonth(cairoMonthOf(now));
  const existing = await prisma.analyticsDocument.findUnique({
    where: { year_month: target },
    select: { id: true },
  });
  if (existing) return null;
  return generateReport(target, now);
};

// The worker's schedule. The scheduler id is the job's name, so every start replaces the schedule instead of adding
// one. A one-off job, its id naming the month, catches up a 1st the worker missed while it was down; once it has run,
// adding it again is a no-op.
export const scheduleAnalyticsJobs = async (queue: Queue, now = new Date()) => {
  await queue.upsertJobScheduler(MONTHLY_REPORT_JOB, monthlyReportSchedule, {
    name: MONTHLY_REPORT_JOB,
    data: {},
    opts: jobOptions,
  });
  const due = previousMonth(cairoMonthOf(now));
  await queue.add(
    MONTHLY_REPORT_JOB,
    {},
    { ...jobOptions, jobId: `${MONTHLY_REPORT_JOB}-${monthLabel(due)}` },
  );
};

export const processAnalyticsJob = async (job: Job) => {
  if (job.name !== MONTHLY_REPORT_JOB) throw new Error(`Unknown analytics job: ${job.name}`);
  await generateDueReport();
};
